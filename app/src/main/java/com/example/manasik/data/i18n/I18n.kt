object I18nManager {
    fun getStrings(code: String): AppStrings {
        return when (code.uppercase()) {
            "EN" -> EnglishStrings
            "AR" -> ArabicStrings
            "ES" -> SpanishStrings
            else -> FrenchStrings
        }
    }

    fun getLanguage(code: String): AppLanguage {
        return AppLanguage.fromCode(code)
    }

    fun getLayoutDirection(code: String): LayoutDirection {
        return if (getLanguage(code).isRtl) LayoutDirection.Rtl else LayoutDirection.Ltr
    }
}

